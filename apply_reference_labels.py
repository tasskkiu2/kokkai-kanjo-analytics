def main() -> None:
    with INPUT.open(encoding="utf-8-sig", newline="") as handle:
        reader = csv.DictReader(handle)
        rows = list(reader)
        fields = reader.fieldnames or []
    missing = {row["speechID"] for row in rows} - set(LABELS)
    extra = set(LABELS) - {row["speechID"] for row in rows}
    if missing or extra:
        raise ValueError(f"label mismatch: missing={missing}, extra={extra}")
    for row in rows:
        emotions, sentiment, confidence, evidence = LABELS[row["speechID"]]
        for name, value in zip(EMOTIONS, emotions):
            row[f"reference_{name}"] = str(value)
        row["reference_sentiment"] = str(sentiment)
        row["annotation_confidence"] = confidence
        row["annotation_evidence"] = evidence
        row["annotator_type"] = "AI-reference"
    with OUTPUT.open("w", encoding="utf-8-sig", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    print(f"wrote {len(rows)} labeled rows to {OUTPUT}")


if __name__ == "__main__":
    main()
